void xport_main(void)
{
    FUNCTION_MARKER(0x801D0320, "PSX.EXE");

    if (!xport_window_init())
    {
        xport_set_exit_code(1);
        return;
    }

    SpuInit();
    ResetCallback();
    SetDispMask(0);
    ResetGraph(3);
    DrawSync(0);

    PSX_RECT clearArea = { 0, 0, 1023, 511 };
    ClearImage(&clearArea, 0, 0, 0);
    DrawSync(0);

    DISPENV display;
    SetDefDispEnv(&display, 0, 0, 512, 240);
    PutDispEnv(&display);
    SetDispMask(1);

    PSX_RECT logoArea = { 440, 200, 42, 24 };
    LoadImagePSX(&logoArea, bootLogoPixels);
    DrawSync(0);
    if (!gpu_present())
    {
        xport_set_exit_code(1);
        return;
    }
    xport_present_complete();

    xport_set_exit_code(Nfs4Main());
}
